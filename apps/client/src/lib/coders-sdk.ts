import { waitForCodersRetry } from "./coders-recovery";

export interface CodersResult {
  response: Response;
  data: unknown;
  ok: boolean;
  status: number;
  requiresAccountAction: boolean;
  accountActionUrl: string | null;
  retry(): Promise<CodersResult>;
}
export interface CodersClient {
  request(path: string, options: RequestInit): Promise<CodersResult>;
  openAccountWindow(url: string): Promise<{ status: string; url?: string }>;
}
let client: Promise<CodersClient>;
export function getCodersClient(): Promise<CodersClient> {
  // This module belongs to Core and is supplied on the isolated app origin.
  const sdkPath = "/_coders/sdk.js";
  return (client ??= import(/* @vite-ignore */ sdkPath).then((module) =>
    module.createClient(),
  ));
}

export function createCodersFetch(
  loadClient = getCodersClient,
  recover = waitForCodersRetry,
): typeof fetch {
  return async (input, init) => {
    const request = new Request(input, init);
    const sdk = await loadClient();
    const options: RequestInit = {
      method: request.method,
      headers: request.headers,
      signal: request.signal,
      // Preserve the multipart boundary generated by Axios, including filenames.
      body: ["GET", "HEAD"].includes(request.method)
        ? undefined
        : await request.blob(),
    };
    let send = () => sdk.request(request.url, options);
    for (;;) {
      let result: CodersResult;
      try {
        result = await send();
      } catch (error) {
        if (request.signal.aborted || typeof error?.retry !== "function")
          throw error;
        await recover({ kind: "unknown", signal: request.signal });
        send = error.retry.bind(error);
        continue;
      }
      if (result.status === 202 || result.requiresAccountAction) {
        await recover({
          kind: result.requiresAccountAction ? "account" : "preparing",
          signal: request.signal,
          openAccount: result.accountActionUrl
            ? () => sdk.openAccountWindow(result.accountActionUrl)
            : undefined,
        });
        send = result.retry.bind(result);
        continue;
      }
      // JSON, binary downloads and Axios HTTP errors all use the original Response.
      return result.response;
    }
  };
}

export const codersFetch = createCodersFetch();
